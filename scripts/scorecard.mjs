// Writes docs/EVALUATION_SCORECARD.md from the spec scenarios and tests/evaluations/coverage.json.
import { readFileSync, writeFileSync } from "node:fs";
const cases = JSON.parse(readFileSync("docs/spec/evaluation_cases.json", "utf8")).cases;
const map = JSON.parse(readFileSync("tests/evaluations/coverage.json", "utf8"));
const order = ["covered", "partial", "needs_logic", "needs_engine", "later"];
const label = { covered: "Covered by passing tests", partial: "Partly covered", needs_logic: "Needs plain code (next)", needs_engine: "Needs the AI reading step and expert rules", later: "Later (infrastructure, payments, interface)" };
const count = Object.fromEntries(order.map((s) => [s, 0]));
for (const c of cases) count[map[c.id].status]++;
let md = `# Evaluation scorecard\n\nGenerated by \`node scripts/scorecard.mjs\`. These are the 60 seed scenarios from the spec. "Covered" means a named passing test proves the rule. Nothing here measures the AI engine, which does not exist yet.\n\n| Status | Scenarios |\n|---|---|\n`;
for (const s of order) md += `| ${label[s]} | ${count[s]} |\n`;
md += `\n## By scenario\n\n| ID | Area | Status | Note |\n|---|---|---|---|\n`;
for (const c of cases) md += `| ${c.id} | ${c.category} | ${map[c.id].status} | ${map[c.id].note || ""} |\n`;

const xcCases = JSON.parse(readFileSync("tests/evaluations/cross_examination_cases.json", "utf8")).cases;
const xcMap = JSON.parse(readFileSync("tests/evaluations/cross_examination_coverage.json", "utf8"));
const xcCount = Object.fromEntries(order.map((s) => [s, 0]));
for (const c of xcCases) xcCount[xcMap[c.id].status]++;
md += `\n## Cross-examination scenarios\n\nTwelve challenges a skeptical expert or opposing party could raise (docs/EXPERT_WITNESS_REVIEW.md). Same rule: "covered" needs a named passing test.\n\n| Status | Scenarios |\n|---|---|\n`;
for (const s of order) md += `| ${label[s]} | ${xcCount[s]} |\n`;
md += `\n| ID | Area | Status | Note |\n|---|---|---|---|\n`;
for (const c of xcCases) md += `| ${c.id} | ${c.category} | ${xcMap[c.id].status} | ${xcMap[c.id].note || ""} |\n`;
writeFileSync("docs/EVALUATION_SCORECARD.md", md);
console.log(order.map((s) => `${s}: ${count[s]}`).join("  "));
console.log("XC  " + order.map((s) => `${s}: ${xcCount[s]}`).join("  "));
